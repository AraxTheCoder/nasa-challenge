"""Build the fully synthetic fixture target (stdlib only). Usage: make_fixture.py <repo_root>"""
import json, math, random, struct, sys, zlib
from pathlib import Path

root = Path(sys.argv[1])
tdir = root / "fixtures" / "targets" / "demo-synthetic"
(tdir / "frames").mkdir(parents=True, exist_ok=True)
for d in ("pipeline", "detect", "web", "data"):
    (root / d).mkdir(exist_ok=True)
    (root / d / ".gitkeep").touch()

W = H = 96
SCALE = 6.15  # arcsec / pixel
RA0, DEC0 = 150.0, 2.2
CX = CY = (W - 1) / 2

def sky(x, y):
    dec = DEC0 - (y - CY) * SCALE / 3600
    ra = RA0 - (x - CX) * SCALE / 3600 / math.cos(math.radians(DEC0))  # east left
    return round(ra, 6), round(dec, 6)

def png(path, px):
    raw = b"".join(b"\x00" + bytes(row) for row in px)
    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d))
    path.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 0, 0, 0, 0))
                     + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))

rng = random.Random(42)
stars = [(rng.uniform(4, W - 4), rng.uniform(4, H - 4), rng.uniform(60, 220)) for _ in range(14)]
times = ["2026-05-01T00:00:00Z", "2026-05-01T12:00:00Z", "2026-05-02T00:00:00Z", "2026-05-02T12:00:00Z"]
mjd0 = 61161.0  # 2026-05-01
waves = [1.10, 1.52, 2.20, 3.40]
mover = [(20.0 + 6.0 * i, 48.0) for i in range(4)]  # moves +x = west

frames, track = [], []
for i, t in enumerate(times):
    px = [[0.0] * W for _ in range(H)]
    for sx, sy, amp in stars + [(mover[i][0], mover[i][1], 200.0)]:
        for y in range(max(0, int(sy) - 5), min(H, int(sy) + 6)):
            for x in range(max(0, int(sx) - 5), min(W, int(sx) + 6)):
                px[y][x] += amp * math.exp(-((x - sx) ** 2 + (y - sy) ** 2) / (2 * 1.3 ** 2))
    out = [[max(0, min(255, int(18 + v + rng.gauss(0, 5)))) for v in row] for row in px]
    fid = f"f{i:03d}"
    png(tdir / "frames" / f"{fid}.png", out)
    frames.append({"id": fid, "time_utc": t, "mjd": mjd0 + 0.5 * i, "epoch": 1, "detector": None,
                   "wavelength_um": waves[i], "image": f"frames/{fid}.png",
                   "obs_id": None, "source_url": None})
    ra, dec = sky(*mover[i])
    track.append({"frame_id": fid, "ra_deg": ra, "dec_deg": dec, "x": mover[i][0], "y": mover[i][1]})

target = {
    "schema_version": "0.1",
    "id": "demo-synthetic",
    "name": "Synthetic demo field (NOT SPHEREx data)",
    "synthetic": True,
    "center": {"ra_deg": RA0, "dec_deg": DEC0},
    "size_arcmin": round(W * SCALE / 60, 2),
    "image": {"width": W, "height": H, "pixel_scale_arcsec": SCALE},
    "provenance": [{"service": "synthetic", "query": "generated by a script, random seed 42; no archive was queried",
                    "retrieved_utc": "2026-11-14T00:00:00Z"}],
    "frames": frames,
    "known_objects": [{"name": "Fake asteroid", "source": "synthetic", "synthetic": True, "positions": track}],
    "detections": [{"id": "d001", "status": "known", "matched_object": "Fake asteroid", "synthetic": True,
                    "score": 0.95, "track": track,
                    "motion": {"rate_arcsec_per_hr": round(6.0 * SCALE / 12, 3), "pa_deg": 270.0}}],
}
(tdir / "target.json").write_text(json.dumps(target, indent=2) + "\n")
(root / "fixtures" / "targets" / "index.json").write_text(json.dumps({
    "schema_version": "0.1",
    "targets": [{"id": "demo-synthetic", "name": target["name"], "synthetic": True,
                 "ra_deg": RA0, "dec_deg": DEC0, "n_frames": len(frames)}]}, indent=2) + "\n")
(root / "fixtures" / "README.md").write_text(
    "# fixtures\n\nTiny committed samples for tests and frontend development. Layout as in `docs/CONTRACTS.md`.\n\n"
    "- `targets/demo-synthetic/`: **fully synthetic** (random stars plus one fake mover, 4 frames, 96×96 px).\n"
    "  It is not SPHEREx data and must never be shown as such. It exists so all three tracks can start\n"
    "  before the pipeline produces a real target.\n")
