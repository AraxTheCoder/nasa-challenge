import assert from 'node:assert/strict';
import { draftStore, discussionLink } from '../community-state.js';
const values = new Map();
const storage = { getItem: k => values.get(k), setItem: (k, v) => values.set(k, v), removeItem: k => values.delete(k) };
const drafts = draftStore(storage);
drafts.save(1, null, { text: 'question', attach: false, kind: 'second_look', title: 'Red source' });
drafts.save(1, 7, { text: 'reply' });
drafts.save(2, null, { text: 'different tile' });
assert.equal(drafts.get(1, null).text, 'question');
assert.equal(draftStore(storage).get(1, null).attach, false);
assert.equal(drafts.get(1, 7).text, 'reply');
assert.equal(drafts.get(2, null).text, 'different tile');
drafts.clear(1, 7);
assert.equal(drafts.get(1, 7).text, '');
assert.equal(drafts.get(1, null).text, 'question');
const broken = draftStore({ getItem() { throw Error(); }, setItem() { throw Error(); }, removeItem() { throw Error(); } });
broken.save(3, null, { text: 'private-mode draft' });
assert.equal(broken.get(3, null).text, 'private-mode draft');
broken.clear(3, null);
assert.equal(broken.get(3, null).text, '');
const link = new URL(discussionLink('https://example.com/web/?ra=12&size=15&tour=1&data=old&api=https%3A%2F%2Fapi.example.com#old', 777, 12));
assert.equal(link.pathname, '/web/');
assert.equal(link.searchParams.get('view'), 'community');
assert.equal(link.searchParams.get('community'), '777');
assert.equal(link.searchParams.get('comment'), '12');
assert.equal(link.searchParams.get('api'), 'https://api.example.com');
assert.equal(link.searchParams.has('size'), false);
assert.equal(link.searchParams.has('data'), false);
assert.equal(link.hash, '');
console.log('Community drafts, storage fallback and share links passed.');
